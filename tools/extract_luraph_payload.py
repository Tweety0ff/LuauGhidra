#!/usr/bin/env python3
"""Extract source passed to an embedded Luraph loadstring without running it.

The outer unpacker is evaluated by Luau, but every embedded [N]=loadstring
reference is replaced with an inert function that records its source and returns
a function which only returns that source. The decoded payload is never compiled
or executed by this helper.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

LOADSTRING_FIELD = re.compile(r"(?P<prefix>\[\s*\d+\s*\]\s*=\s*)loadstring\b")


def lua_long_string(value: str) -> str:
    """Return a Luau long-bracket string whose closing token is absent in value."""
    for level in range(0, 128):
        equals = "=" * level
        closing = "]" + equals + "]"
        if closing not in value:
            opening = "[" + equals + "["
            return opening + value + closing
    raise ValueError("could not choose a safe Luau long-string delimiter")


def _field_matches_outside_literals(source: str) -> list[re.Match[str]]:
    """Find target assignments while skipping Lua strings and comments."""
    matches: list[re.Match[str]] = []
    i = 0
    n = len(source)
    while i < n:
        if source.startswith("--", i):
            long_open = re.match(r"--\[(=*)\[", source[i:])
            if long_open:
                close = "]" + long_open.group(1) + "]"
                end = source.find(close, i + long_open.end())
                i = n if end < 0 else end + len(close)
            else:
                end = source.find("\n", i + 2)
                i = n if end < 0 else end + 1
            continue
        if source[i] in ("'", '"'):
            quote = source[i]
            i += 1
            while i < n:
                if source[i] == "\\":
                    i += 2
                elif source[i] == quote:
                    i += 1
                    break
                else:
                    i += 1
            continue
        if source[i] == "[":
            long_open = re.match(r"\[(=*)\[", source[i:])
            if long_open:
                close = "]" + long_open.group(1) + "]"
                end = source.find(close, i + long_open.end())
                i = n if end < 0 else end + len(close)
                continue
        match = LOADSTRING_FIELD.match(source, i)
        if match:
            matches.append(match)
            i = match.end()
        else:
            i += 1
    return matches


def replace_loadstring_fields(source: str) -> tuple[str, int]:
    """Redirect explicit numeric table fields from loadstring to our inert stub."""
    matches = _field_matches_outside_literals(source)
    if not matches:
        raise ValueError("no numeric table field assigned directly to loadstring was found")
    pieces: list[str] = []
    cursor = 0
    for match in matches:
        pieces.append(source[cursor:match.start()])
        pieces.append(match.group("prefix") + "__LPH_CAPTURE_LOADSTRING")
        cursor = match.end()
    pieces.append(source[cursor:])
    return "".join(pieces), len(matches)


def build_runner(source: str) -> tuple[str, int]:
    patched, count = replace_loadstring_fields(source)
    script = r'''-- Generated by tools/extract_luraph_payload.py.
local realPrint = print
local captured = {}

-- Only this inert replacement is visible to the obfuscated wrapper.
-- It records source text and returns a no-op closure; it never compiles it.
__LPH_CAPTURE_LOADSTRING = function(source, chunkName)
    if type(source) ~= "string" then
        return nil, "captured loadstring argument was not a string"
    end
    table.insert(captured, source)
    return function(...)
        return source
    end
end

local protectedSource = SOURCE_LITERAL
local loader, compileError = loadstring(protectedSource, "@input.luau")
if not loader then
    error("could not compile outer Luraph wrapper: " .. tostring(compileError))
end

-- Run the unpacking wrapper only. Any loadstring it requests is intercepted.
local ok, result = pcall(loader)
if not ok then
    realPrint("__LPH_WRAPPER_ERROR__" .. tostring(result))
end
if type(result) == "string" then
    table.insert(captured, result)
end

for index, payload in ipairs(captured) do
    realPrint("__LPH_BEGIN__" .. index .. "__" .. #payload)
    for offset = 1, #payload, 2048 do
        local bytes = {}
        local last = math.min(offset + 2047, #payload)
        for pos = offset, last do
            bytes[#bytes + 1] = string.format("%02x", string.byte(payload, pos))
        end
        realPrint("__LPH_DATA__" .. table.concat(bytes))
    end
    realPrint("__LPH_END__" .. index)
end
'''.replace("SOURCE_LITERAL", lua_long_string(patched))
    return script, count


def parse_captures(stdout: str) -> list[bytes]:
    captures: list[bytes] = []
    current: list[str] | None = None
    expected_length: int | None = None

    for line in stdout.splitlines():
        if line.startswith("__LPH_BEGIN__"):
            current = []
            try:
                expected_length = int(line.rsplit("__", 1)[1])
            except (IndexError, ValueError):
                expected_length = None
        elif line.startswith("__LPH_DATA__") and current is not None:
            current.append(line[len("__LPH_DATA__"):])
        elif line.startswith("__LPH_END__") and current is not None:
            raw = bytes.fromhex("".join(current))
            if expected_length is not None and len(raw) != expected_length:
                raise ValueError(
                    f"captured payload length mismatch: expected {expected_length}, got {len(raw)}"
                )
            captures.append(raw)
            current = None
            expected_length = None

    return captures


def find_luau(explicit: Path | None, repo_root: Path) -> Path:
    if explicit is not None:
        candidate = explicit.expanduser().resolve()
        if not candidate.is_file():
            raise FileNotFoundError(f"Luau executable not found: {candidate}")
        return candidate

    names = ["luau.exe", "luau"] if sys.platform == "win32" else ["luau", "luau.exe"]
    for name in names:
        candidate = repo_root / "bin" / name
        if candidate.is_file():
            return candidate
    for name in names:
        found = shutil.which(name)
        if found:
            return Path(found)
    raise FileNotFoundError(
        "Luau CLI not found; build it with python build_luau.py or pass --luau"
    )


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Safely extract source handed to an embedded Luraph loadstring."
    )
    parser.add_argument("input", type=Path, help="obfuscated .lua/.luau source")
    parser.add_argument(
        "-o", "--output-dir", type=Path,
        help="directory for extracted payloads (default: <input>.extracted/)",
    )
    parser.add_argument("--luau", type=Path, help="path to the Luau CLI executable")
    parser.add_argument("--timeout", type=int, default=120, help="unpacker timeout in seconds (default: 120)")
    args = parser.parse_args()

    source_path = args.input.expanduser().resolve()
    if not source_path.is_file():
        parser.error(f"input file not found: {source_path}")

    # Preserve each input byte. Luraph output is ASCII, while latin-1 also keeps
    # arbitrary byte values round-trippable if a protected file contains them.
    source = source_path.read_bytes().decode("latin-1")
    try:
        runner, replacements = build_runner(source)
        luau = find_luau(args.luau, Path(__file__).resolve().parents[1])
    except (ValueError, FileNotFoundError) as exc:
        print(f"[!] {exc}", file=sys.stderr)
        return 2

    output_dir = (args.output_dir or source_path.with_name(source_path.stem + ".extracted")).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="luraph_extract_") as temp_dir:
        runner_path = Path(temp_dir) / "extract_wrapper.luau"
        runner_path.write_bytes(runner.encode("latin-1"))
        try:
            proc = subprocess.run(
                [str(luau), str(runner_path)],
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                encoding="ascii",
                errors="replace",
                timeout=max(1, args.timeout),
                check=False,
            )
        except subprocess.TimeoutExpired:
            print(f"[!] unpacker exceeded {args.timeout}s; no payload was executed", file=sys.stderr)
            return 3
        except OSError as exc:
            print(f"[!] could not start Luau: {exc}", file=sys.stderr)
            return 3

    try:
        captures = parse_captures(proc.stdout)
    except ValueError as exc:
        print(f"[!] malformed capture output: {exc}", file=sys.stderr)
        return 4

    # A captured loadstring argument and the wrapper's return value can be the
    # same string. Deduplicate by bytes while preserving discovery order.
    unique: list[bytes] = []
    seen: set[bytes] = set()
    for payload in captures:
        if payload not in seen:
            seen.add(payload)
            unique.append(payload)

    if proc.returncode != 0:
        print(f"[!] Luau exited with status {proc.returncode}", file=sys.stderr)
    for line in proc.stdout.splitlines():
        if line.startswith("__LPH_WRAPPER_ERROR__"):
            print("[!] wrapper stopped after capture: " + line[len("__LPH_WRAPPER_ERROR__"):], file=sys.stderr)
    if proc.stderr.strip():
        print(proc.stderr.rstrip(), file=sys.stderr)

    if not unique:
        print(
            "[!] no source was passed to the intercepted loadstring field; "
            "the wrapper may need another loader-specific stub",
            file=sys.stderr,
        )
        return 5

    print(f"[*] replaced {replacements} embedded loadstring field(s)")
    for index, payload in enumerate(unique, 1):
        out_path = output_dir / f"{source_path.stem}.payload-{index:02d}.luau"
        out_path.write_bytes(payload)
        print(f"[+] extracted {len(payload):,} bytes -> {out_path}")
    print("[*] captured source only; decoded payload was not compiled or executed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
