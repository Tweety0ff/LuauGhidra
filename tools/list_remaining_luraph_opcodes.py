#!/usr/bin/env python3
"""Export unresolved handler bodies for a Luraph VM dispatcher.

Run from the repository root:
    python tools/list_remaining_luraph_opcodes.py

By default this reads the extracted VM chunk in /tmp, resolves dispatcher #14,
groups opcode numbers that share the exact same AST handler body, and writes
analysis/luraph-v15.2-dispatcher14-remaining.md.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORE_DIR = ROOT / "core"
VM_DIR = CORE_DIR / "obfuscators" / "luraph_v15"

# Make vmmap.py and its harness importable when this tool is run from repo root.
sys.path.insert(0, str(CORE_DIR))
sys.path.insert(0, str(VM_DIR))

import vmmap  # noqa: E402


# Opcode values whose handler semantics have already been manually traced.
# If multiple opcode values resolve to the same AST body, the whole group is
# treated as covered; the generated report shows those aliases explicitly.
# A source-location group is covered only when EVERY opcode in that group is
# already mapped. A mixed group is ambiguous and must remain in the pending
# report; never infer that its unmapped values are aliases from a partial hit.
MAPPED_OPCODES = {
    *range(0, 27),
    *range(27, 47),
    *range(49, 56),
    47, 48,
    56, 57, 58,
    *range(59, 62),
    *range(63, 70),
    *range(71, 84),
    *range(84, 95),
    *range(96, 99),
    *range(100, 104),
    105,
    *range(107, 113),
    *range(113, 136),
    137, 138,
    *range(139, 164),
    *range(164, 187),
    188, 189,
    62, 70,
    95, 99,
    104, 106,
    136, 187,
}


def format_ops(values: list[int]) -> str:
    return ", ".join(str(x) for x in sorted(values))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source",
        nargs="?",
        type=Path,
        default=Path("/tmp/main-luraph.bootstrap.chunk_249311_138937462.luau"),
        help="extracted VM source (default: the current Codespaces /tmp chunk)",
    )
    parser.add_argument("--dispatcher", type=int, default=14, help="1-based dispatcher index (default: 14)")
    parser.add_argument("--max-op", type=int, default=256, help="scan opcode values in range [0, max-op)")
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("analysis/luraph-v15.2-dispatcher14-remaining.md"),
        help="Markdown report path (default: analysis/luraph-v15.2-dispatcher14-remaining.md)",
    )
    args = parser.parse_args()

    source = args.source.expanduser().resolve()
    if not source.is_file():
        parser.error(
            "VM source not found: %s. Restore it from dump.txt using the extraction steps in the project notes."
            % source
        )

    try:
        root = vmmap.load_ast(str(source))
    except Exception as exc:
        parser.error("could not parse VM source with Luau AST: %s" % exc)

    with source.open("r", encoding="latin-1") as handle:
        lines = handle.read().split("\n")

    dispatchers = vmmap.find_dispatchers(root)
    if not 1 <= args.dispatcher <= len(dispatchers):
        parser.error(
            "dispatcher %d does not exist; source contains %d dispatcher(s)"
            % (args.dispatcher, len(dispatchers))
        )

    dispatcher = dispatchers[args.dispatcher - 1]
    grouped = vmmap.handler_map(dispatcher, lines, max_op=args.max_op)
    groups = sorted(grouped.values(), key=lambda item: min(item["ops"]))

    covered_groups = []
    remaining_groups = []
    for item in groups:
        ops = sorted(item["ops"])
        if set(ops).issubset(MAPPED_OPCODES):
            covered_groups.append(item)
        else:
            remaining_groups.append(item)

    covered_ops = sorted({op for item in covered_groups for op in item["ops"]})
    remaining_ops = sorted({op for item in remaining_groups for op in item["ops"]})
    aliases = sorted(set(covered_ops) - MAPPED_OPCODES)

    out = args.output
    if not out.is_absolute():
        out = ROOT / out
    out.parent.mkdir(parents=True, exist_ok=True)

    report: list[str] = [
        "# Remaining Luraph v15.2 dispatcher handlers",
        "",
        "Generated by `tools/list_remaining_luraph_opcodes.py`.",
        "",
        "- Source: `%s`" % source.name,
        "- Dispatcher: #%d (`op=%s`, instruction array `%s`, PC `%s`)"
        % (args.dispatcher, dispatcher["op"], dispatcher["arr"], dispatcher["pc"]),
        "- Distinct handler-body groups found: **%d**" % len(groups),
        "- Groups covered by the known mapping: **%d**" % len(covered_groups),
        "- Groups still to inspect: **%d**" % len(remaining_groups),
        "- Known opcode values: **%d**" % len(MAPPED_OPCODES),
        "- Additional opcode values sharing an already mapped handler: **%s**"
        % (format_ops(aliases) if aliases else "none"),
        "",
        "The grouping is by AST source location. If an unlisted opcode resolves to the exact same handler body as a known opcode, it is shown as an alias and does not need a separate semantic analysis.",
        "",
        "## Remaining opcode values",
        "",
        format_ops(remaining_ops) if remaining_ops else "None.",
        "",
        "## Remaining handler bodies",
        "",
    ]

    if not remaining_groups:
        report.append("No unclassified handler groups remain.")
    else:
        for index, item in enumerate(remaining_groups, 1):
            ops = sorted(item["ops"])
            location = item["node"].get("location", "unknown")
            body = vmmap.text_of(lines, item["node"]).strip()
            report.extend(
                [
                    "### Handler group %d — opcode(s): %s" % (index, format_ops(ops)),
                    "",
                    "AST location: `%s`" % location,
                    "",
                    "```luau",
                    body,
                    "```",
                    "",
                ]
            )

    out.write_text("\n".join(report).rstrip() + "\n", encoding="utf-8")
    print("Dispatcher #%d: %d handler groups total, %d still to inspect." %
          (args.dispatcher, len(groups), len(remaining_groups)))
    print("Remaining opcode values: %s" % (format_ops(remaining_ops) if remaining_ops else "none"))
    print("Wrote: %s" % out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
